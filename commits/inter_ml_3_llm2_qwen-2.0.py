CHUNK_SIZE = 60_000
CHUNK_OVERLAP = 5_000

CHUNK_STEP = CHUNK_SIZE - CHUNK_OVERLAP


# ------------------------------------------------------------
# Tokenize transcript
# ------------------------------------------------------------

def tokenize_transcript(text):
    """
    Tokenize transcript using the official Qwen tokenizer.

    Returns the token IDs used by Qwen.
    """

    if not isinstance(text, str):
        raise TypeError(
            "Transcript must be a string."
        )

    if not text.strip():
        raise ValueError(
            "Transcript cannot be empty."
        )

    token_ids = tokenizer.encode(
        text,
        add_special_tokens=False
    )

    return token_ids


# ------------------------------------------------------------
# Count tokens
# ------------------------------------------------------------

def count_tokens(text):
    """
    Return the number of Qwen tokens in the transcript.
    """

    token_ids = tokenize_transcript(text)

    return len(token_ids)


# ------------------------------------------------------------
# Create overlapping token chunks
# ------------------------------------------------------------

def create_token_chunks(
    token_ids,
    chunk_size=CHUNK_SIZE,
    overlap=CHUNK_OVERLAP
):
    """
    Split token IDs into overlapping chunks.

    Example:

        Chunk 1: 0       → 60,000
        Chunk 2: 55,000  → 115,000
        Chunk 3: 110,000 → 170,000

    The chunks overlap by 5,000 tokens.
    """

    if not isinstance(token_ids, list):
        raise TypeError(
            "token_ids must be a list."
        )

    if chunk_size <= 0:
        raise ValueError(
            "chunk_size must be greater than 0."
        )

    if overlap < 0:
        raise ValueError(
            "overlap cannot be negative."
        )

    if overlap >= chunk_size:
        raise ValueError(
            "overlap must be smaller than chunk_size."
        )

    step = chunk_size - overlap

    chunks = []

    start = 0
    total_tokens = len(token_ids)

    while start < total_tokens:

        end = min(
            start + chunk_size,
            total_tokens
        )

        chunk = token_ids[start:end]

        chunks.append(chunk)

        # Stop when we've reached the end
        if end >= total_tokens:
            break

        start += step

    return chunks


# ------------------------------------------------------------
# Decode token chunks back into text
# ------------------------------------------------------------

def decode_token_chunks(chunks):
    """
    Convert token-ID chunks back into text.

    Returns a list of text chunks.
    """

    if not isinstance(chunks, list):
        raise TypeError(
            "chunks must be a list."
        )

    text_chunks = []

    for chunk in chunks:

        text = tokenizer.decode(
            chunk,
            skip_special_tokens=True
        )

        text_chunks.append(text)

    return text_chunks


# ------------------------------------------------------------
# Complete transcript chunking pipeline
# ------------------------------------------------------------

def chunk_transcript(
    transcript,
    chunk_size=CHUNK_SIZE,
    overlap=CHUNK_OVERLAP
):
    """
    Tokenize a transcript and split it into overlapping
    text chunks.

    Returns a structured dictionary containing:

        - total token count
        - token chunks
        - decoded text chunks
        - chunk metadata
    """

    token_ids = tokenize_transcript(
        transcript
    )

    chunks = create_token_chunks(
        token_ids,
        chunk_size=chunk_size,
        overlap=overlap
    )

    text_chunks = decode_token_chunks(
        chunks
    )

    chunk_data = []

    for i, (token_chunk, text_chunk) in enumerate(
        zip(chunks, text_chunks)
    ):

        start_token = i * (
            chunk_size - overlap
        )

        end_token = start_token + len(
            token_chunk
        )

        chunk_data.append({
            "chunk_id": i + 1,
            "start_token": start_token,
            "end_token": end_token,
            "token_count": len(token_chunk),
            "text": text_chunk
        })

    return {
        "total_tokens": len(token_ids),
        "total_chunks": len(chunk_data),
        "chunk_size": chunk_size,
        "overlap": overlap,
        "chunks": chunk_data
    }


# ------------------------------------------------------------
# Get only text chunks
# ------------------------------------------------------------

def get_text_chunks(
    transcript,
    chunk_size=CHUNK_SIZE,
    overlap=CHUNK_OVERLAP
):
    """
    Convenience function that returns only the decoded
    transcript chunks.
    """

    result = chunk_transcript(
        transcript,
        chunk_size=chunk_size,
        overlap=overlap
    )

    return [
        chunk["text"]
        for chunk in result["chunks"]
    ]



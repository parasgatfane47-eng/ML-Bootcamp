# 4. PREPARE TRANSCRIPT CHUNKS
# ============================================================

def prepare_transcript_chunks(
    refined_transcript
):

    """
    Complete timestamp parsing + time-based chunking.
    """

    segments = parse_timestamped_transcript(
        refined_transcript
    )

    chunks = create_time_chunks(
        segments
    )

    total_duration = max(
        segment["end"]
        for segment in segments
    )


    print(
        "\nTranscript parsing complete."
    )

    print(
        f"Transcript segments: "
        f"{len(segments)}"
    )

    print(
        f"Approximate recording duration: "
        f"{seconds_to_timestamp(total_duration)}"
    )

    print(
        f"Time chunks created: "
        f"{len(chunks)}"
    )


    for chunk in chunks:

        print(
            f"  Chunk {chunk['chunk_id']}: "
            f"{seconds_to_timestamp(chunk['start_time'])} "
            f"→ "
            f"{seconds_to_timestamp(chunk['end_time'])}"
        )


    return {
        "segments": segments,
        "chunks": chunks,
        "total_duration": total_duration
    }



# 2. PARSE TIMESTAMPED TRANSCRIPT
# ============================================================

def parse_timestamped_transcript(transcript):

    """
    Parses the refined WhisperX text transcript.

    Expected format:

    [00:14 – 00:30] SPEAKER_01: text

    or

    [00:53 - 02:24] SPEAKER_00: text

    Both normal hyphen and en/em dash are supported.

    Wrapped lines belonging to the same timestamped
    segment are automatically joined.
    """

    if not isinstance(
        transcript,
        str
    ):

        raise TypeError(
            "Transcript must be a string."
        )

    if not transcript.strip():

        raise ValueError(
            "Transcript is empty."
        )


    # --------------------------------------------------------
    # Timestamp pattern
    # --------------------------------------------------------

    timestamp_pattern = re.compile(
        r"""
        ^\s*
        \[
        (\d{1,2}:\d{2}(?::\d{2})?(?:[.,]\d+)?)
        \s*[-–—]\s*
        (\d{1,2}:\d{2}(?::\d{2})?(?:[.,]\d+)?)
        \]
        \s*
        (.*)
        $
        """,
        re.VERBOSE
    )


    segments = []

    current_start = None
    current_end = None
    current_text = []


    # --------------------------------------------------------
    # Read transcript line by line
    # --------------------------------------------------------

    for line in transcript.splitlines():

        match = timestamp_pattern.match(
            line
        )

        # ----------------------------------------------------
        # New timestamped segment
        # ----------------------------------------------------

        if match:

            # Save previous segment
            if (
                current_start is not None
                and current_end is not None
            ):

                text = " ".join(
                    current_text
                ).strip()

                if text:

                    segments.append(
                        {
                            "start": current_start,
                            "end": current_end,
                            "text": text
                        }
                    )


            # Start new segment
            current_start = timestamp_to_seconds(
                match.group(1)
            )

            current_end = timestamp_to_seconds(
                match.group(2)
            )

            first_line_text = (
                match.group(3).strip()
            )

            current_text = []

            if first_line_text:

                current_text.append(
                    first_line_text
                )


        # ----------------------------------------------------
        # Continuation of current segment
        # ----------------------------------------------------

        else:

            line = line.strip()

            if (
                line
                and current_start is not None
            ):

                current_text.append(
                    line
                )


    # --------------------------------------------------------
    # Save final segment
    # --------------------------------------------------------

    if (
        current_start is not None
        and current_end is not None
    ):

        text = " ".join(
            current_text
        ).strip()

        if text:

            segments.append(
                {
                    "start": current_start,
                    "end": current_end,
                    "text": text
                }
            )


    # --------------------------------------------------------
    # Validation
    # --------------------------------------------------------

    if not segments:

        raise ValueError(
            "No timestamped transcript segments were found. "
            "Expected format such as "
            "[00:14 - 00:30] SPEAKER_01: text"
        )


    # --------------------------------------------------------
    # Sort by start time
    # --------------------------------------------------------

    segments.sort(
        key=lambda x: x["start"]
    )


    return segments



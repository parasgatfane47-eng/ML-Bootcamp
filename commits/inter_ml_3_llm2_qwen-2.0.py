def make_context_safe(
    combined_analyses
):

    token_count = count_text_tokens(
        combined_analyses
    )


    if token_count <= FINAL_INPUT_TOKEN_LIMIT:

        return combined_analyses


    print(
        "\nCombined analysis is large."
    )

    print(
        f"Current tokens: {token_count:,}"
    )

    print(
        "Reducing analysis before final Gemini call..."
    )


    sections = combined_analyses.split(
        "\n\n===== CHUNK "
    )


    batches = []

    current_batch = []
    current_tokens = 0


    for section in sections:

        section = section.strip()

        if not section:

            continue


        section_tokens = count_text_tokens(
            section
        )


        if (
            current_batch
            and
            current_tokens
            + section_tokens
            > REDUCTION_BATCH_TOKEN_LIMIT
        ):

            batches.append(
                "\n\n===== CHUNK ".join(
                    current_batch
                )
            )

            current_batch = []

            current_tokens = 0


        current_batch.append(
            section
        )

        current_tokens += section_tokens


    if current_batch:

        batches.append(
            "\n\n===== CHUNK ".join(
                current_batch
            )
        )


    reduced_outputs = []


    for index, batch in enumerate(
        batches,
        start=1
    ):

        print(
            f"Reducing batch "
            f"{index}/{len(batches)}..."
        )


        reduced = reduce_analysis_batch(
            [batch]
        )


        reduced_outputs.append(
            reduced
        )


    return "\n\n".join(
        reduced_outputs
    )



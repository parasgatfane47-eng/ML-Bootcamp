CHUNK_SIZE = 60_000
CHUNK_OVERLAP = 5_000


def tokenize_transcript(text):

    if not isinstance(text, str):
        raise TypeError(
            "Transcript must be a string."
        )

    if not text.strip():
        raise ValueError(
            "Transcript cannot be empty."
        )

    return tokenizer.encode(
        text,
        add_special_tokens=False
    )


def create_token_chunks(
    token_ids,
    chunk_size=CHUNK_SIZE,
    overlap=CHUNK_OVERLAP
):

    if not isinstance(
        token_ids,
        list
    ):
        raise TypeError(
            "token_ids must be a list."
        )

    if overlap >= chunk_size:
        raise ValueError(
            "Overlap must be smaller than chunk size."
        )

    step = chunk_size - overlap

    chunks = []

    start = 0

    while start < len(token_ids):

        end = min(
            start + chunk_size,
            len(token_ids)
        )

        chunks.append(
            token_ids[start:end]
        )

        if end >= len(token_ids):
            break

        start += step

    return chunks


def decode_token_chunks(chunks):

    return [
        tokenizer.decode(
            chunk,
            skip_special_tokens=True
        )
        for chunk in chunks
    ]


def chunk_transcript(
    transcript,
    chunk_size=CHUNK_SIZE,
    overlap=CHUNK_OVERLAP
):

    token_ids = tokenize_transcript(
        transcript
    )

    token_chunks = create_token_chunks(
        token_ids,
        chunk_size,
        overlap
    )

    text_chunks = decode_token_chunks(
        token_chunks
    )

    step = chunk_size - overlap

    chunks = []

    for i, (
        token_chunk,
        text_chunk
    ) in enumerate(
        zip(
            token_chunks,
            text_chunks
        )
    ):

        start_token = i * step

        chunks.append({
            "chunk_id": i + 1,
            "start_token": start_token,
            "end_token": (
                start_token +
                len(token_chunk)
            ),
            "token_count": len(
                token_chunk
            ),
            "text": text_chunk
        })

    return {
        "total_tokens": len(
            token_ids
        ),
        "total_chunks": len(
            chunks
        ),
        "chunks": chunks
    }



# 3. CREATE TIME-BASED CHUNKS
# ============================================================

def create_time_chunks(segments):

    """
    Creates:

        10-minute chunks
        30-second overlap

    Example for a 19-minute recording:

        Chunk 1: 00:00 - 10:00
        Chunk 2: 09:30 - 19:00

    Transcript segments are never cut in the middle.
    A segment is included if it overlaps the chunk window.
    """

    if not segments:

        raise ValueError(
            "No transcript segments available."
        )


    # --------------------------------------------------------
    # Recording boundaries
    # --------------------------------------------------------

    recording_start = 0.0

    recording_end = max(
        segment["end"]
        for segment in segments
    )


    # --------------------------------------------------------
    # Create windows
    # --------------------------------------------------------

    chunks = []

    chunk_start = recording_start

    chunk_id = 1


    while chunk_start < recording_end:

        chunk_end = min(
            chunk_start
            + CHUNK_DURATION_SECONDS,
            recording_end
        )


        # ----------------------------------------------------
        # Find segments overlapping this time window
        # ----------------------------------------------------

        chunk_segments = []

        for segment in segments:

            segment_start = segment["start"]
            segment_end = segment["end"]

            overlaps = (
                segment_end > chunk_start
                and segment_start < chunk_end
            )

            if overlaps:

                chunk_segments.append(
                    segment
                )


        # ----------------------------------------------------
        # Build chunk text
        # ----------------------------------------------------

        chunk_lines = []

        for segment in chunk_segments:

            start_label = seconds_to_timestamp(
                segment["start"]
            )

            end_label = seconds_to_timestamp(
                segment["end"]
            )

            chunk_lines.append(
                f"[{start_label} - {end_label}] "
                f"{segment['text']}"
            )


        chunk_text = "\n".join(
            chunk_lines
        ).strip()


        if chunk_text:

            chunks.append(
                {
                    "chunk_id": chunk_id,

                    "start_time": chunk_start,

                    "end_time": chunk_end,

                    "duration_seconds": (
                        chunk_end
                        - chunk_start
                    ),

                    "text": chunk_text
                }
            )

            chunk_id += 1


        # ----------------------------------------------------
        # Move to next window
        # ----------------------------------------------------

        chunk_start += CHUNK_STEP_SECONDS


    if not chunks:

        raise ValueError(
            "No chunks could be created from transcript."
        )


    return chunks



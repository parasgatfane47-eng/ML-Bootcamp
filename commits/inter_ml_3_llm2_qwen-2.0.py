# 13. VALIDATE FINAL OUTPUT
# ============================================================

def validate_final_output(
    raw_output
):

    if not raw_output:

        raise ValueError(
            "Final Gemini output is empty."
        )


    cleaned = raw_output.strip()


    # --------------------------------------------------------
    # Remove markdown JSON fences if Gemini adds them
    # --------------------------------------------------------

    if cleaned.startswith(
        "```json"
    ):

        cleaned = cleaned[
            len("```json"):
        ]

    elif cleaned.startswith(
        "```"
    ):

        cleaned = cleaned[
            len("```"):
        ]


    if cleaned.endswith(
        "```"
    ):

        cleaned = cleaned[
            :-len("```")
        ]


    cleaned = cleaned.strip()


    # --------------------------------------------------------
    # Extract JSON object
    # --------------------------------------------------------

    first_brace = cleaned.find(
        "{"
    )

    last_brace = cleaned.rfind(
        "}"
    )


    if (
        first_brace == -1
        or last_brace == -1
        or last_brace <= first_brace
    ):

        raise ValueError(
            "Could not find valid JSON object "
            "in Gemini output."
        )


    json_text = cleaned[
        first_brace:
        last_brace + 1
    ]


    try:

        parsed = json.loads(
            json_text
        )

    except json.JSONDecodeError as error:

        raise ValueError(
            "Gemini returned invalid JSON.\n"
            f"Error: {error}\n\n"
            f"Raw output:\n{raw_output}"
        )


    # --------------------------------------------------------
    # Pydantic validation
    # --------------------------------------------------------

    try:

        validated = LLM2Output.model_validate(
            parsed
        )

    except ValidationError as error:

        raise ValueError(
            "Final output failed Pydantic validation.\n\n"
            f"{error}"
        )


    return validated


